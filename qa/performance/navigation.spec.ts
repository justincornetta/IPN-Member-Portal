import { test, expect, type Page } from "@playwright/test"
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const found: string[]=[]; errors.set(page,found)
  page.on("pageerror",error=>found.push(error.message))
  page.on("console",message=>{if(message.type()==="error")found.push(message.text())})
})
test.afterEach(async ({page})=>{
  expect(errors.get(page)).toEqual([])
  await expect(page.locator("nextjs-portal [data-nextjs-dialog]")).toHaveCount(0)
})
for(const width of [1440,1280,390]) test(`Community and Events navigation at ${width}px`,async({page},info)=>{
  await page.setViewportSize({width,height:950})
  await page.goto("/dashboard/events")
  await expect(page.getByRole("heading",{name:"Events",exact:true})).toBeVisible()
  await expect(page.getByRole("heading",{name:"Community research conversation",exact:true})).toBeVisible()
  await page.screenshot({path:info.outputPath(`events-${width}.png`),fullPage:true})
  await page.getByRole("link",{name:"Community",exact:true}).click()
  await expect(page.getByRole("heading",{name:"Member Directory",exact:true})).toBeVisible()
  await expect(page.getByRole("button",{name:/Member 0000 Example/})).toBeVisible()
  await page.screenshot({path:info.outputPath(`community-${width}.png`),fullPage:true})
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)
  expect(overflow).toBe(false)
  await page.getByRole("button",{name:"Load more members",exact:true}).click()
  await expect(page.getByRole("button",{name:/Member 0119 Example/})).toBeAttached()
  await page.getByRole("link",{name:"Events",exact:true}).click()
  await expect(page.getByRole("heading",{name:"Community research conversation",exact:true})).toBeVisible()
  await page.getByRole("link",{name:"Browse past recordings"}).click()
  await expect(page.getByRole("heading",{name:"Recordings",exact:true})).toBeVisible()
  await page.getByRole("button",{name:"IPN Labs (1)",exact:true}).click()
  await expect(page.getByRole("heading",{name:"Research methods recording"})).toBeVisible()
  await page.getByRole("link",{name:"Upcoming events",exact:true}).click()
  await expect(page.getByRole("heading",{name:"Community research conversation",exact:true})).toBeVisible()
})
test("loading feedback keeps navigation usable on a slow transition",async({page,context},info)=>{
  await page.goto("/dashboard/events")
  await expect(page.getByRole("heading",{name:"Community research conversation",exact:true})).toBeVisible()
  await context.addCookies([{name:"qa-delay",value:"800",domain:"127.0.0.1",path:"/"}])
  await page.getByRole("link",{name:"Community",exact:true}).click()
  await expect(page.getByRole("status").filter({hasText:"Loading, please wait"})).toBeVisible({timeout:1500})
  await page.screenshot({path:info.outputPath("community-loading.png"),fullPage:true})
  await expect(page.getByRole("link",{name:"Events",exact:true})).toBeEnabled()
  await expect(page.getByRole("button",{name:/Member 0000 Example/})).toBeVisible()
  await expect(page.getByText("Loading, please wait…",{exact:true})).toHaveCount(0)
  await context.clearCookies()
})
test("failed directory read shows error and retry restores the page",async({page,context},info)=>{
  await context.addCookies([{name:"qa-fail",value:"profiles",domain:"127.0.0.1",path:"/"}])
  await page.goto("/dashboard/directory")
  await expect(page.getByRole("alert").filter({hasText:"We couldn’t load this page."})).toContainText("We couldn’t load this page.")
  await page.screenshot({path:info.outputPath("community-error.png"),fullPage:true})
  await context.clearCookies()
  await page.getByRole("button",{name:"Try again",exact:true}).click()
  await expect(page.getByRole("button",{name:/Member 0000 Example/})).toBeVisible()
})
test("search resolves members beyond the first loaded page",async({page})=>{
  await page.goto("/dashboard/directory")
  await expect(page.getByRole("button",{name:/Member 0000 Example/})).toBeVisible()
  await page.getByRole("textbox").first().fill("Member 0124")
  await expect(page.getByRole("button",{name:/Member 0124 Example/})).toBeVisible()
  await expect(page.getByRole("button",{name:"Load more members",exact:true})).toHaveCount(0)
})

test("failed events read shows error and retry restores the page",async({page,context})=>{
  await context.addCookies([{name:"qa-fail",value:"events",domain:"127.0.0.1",path:"/"}])
  await page.goto("/dashboard/events")
  await expect(page.getByRole("alert").filter({hasText:"We couldn’t load this page."})).toBeVisible()
  await context.clearCookies()
  await page.getByRole("button",{name:"Try again",exact:true}).click()
  await expect(page.getByRole("heading",{name:"Community research conversation",exact:true})).toBeVisible()
})

test("preview controls preserve the host and apply failure and reset modes",async({page})=>{
  await page.goto("/performance-preview")
  await page.getByRole("link",{name:"Try Community error state",exact:true}).click()
  await expect(page).toHaveURL("http://127.0.0.1:4341/dashboard/directory")
  await expect(page.getByRole("alert").filter({hasText:"We couldn’t load this page."})).toBeVisible()
  await page.goto("/performance-preview")
  await page.getByRole("link",{name:"Reset preview",exact:true}).click()
  await expect(page.getByRole("button",{name:/Member 0000 Example/})).toBeVisible()
})
