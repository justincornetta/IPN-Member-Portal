import { test, expect } from "@playwright/test"

for (const width of [1440, 1280, 390]) {
  test(`guided media intake at ${width}px, cancellation retains the queue`, async ({ page }) => {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    const errors: string[] = []
    page.on("pageerror", (error) => errors.push(error.message))
    page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()) })
    let submissions = 0
    page.on("request", (request) => {
      if (request.method() === "POST" && request.url().endsWith("/api/admin/workflows")) submissions++
    })
    await page.goto("/workflow-preview/media")
    await page.getByRole("button", { name: "New media request", exact: true }).click()
    const form = page.getByRole("form", { name: "New media request" })
    await page.evaluate(() => document.fonts.ready)
    await form.getByRole("heading", { name: "New media request", exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: `docs/media-guided-intake/screenshots/idea-${width}.png` })
    if (width === 1440) {
      await form.getByRole("navigation", { name: "Request steps" }).screenshot({
        path: "docs/media-guided-intake/screenshots/step-navigation.png"
      })
    }
    await form.getByLabel("Give it a name", { exact: true }).fill("Mentorship interest form")
    await form.getByLabel("Team or project").fill("Community")
    await form.getByLabel("What's it about?").fill("Invite members to help shape IPN's mentorship program by joining a focus group.")
    await form.getByRole("button", { name: "Continue", exact: true }).click()
    await form.getByLabel("Post by", { exact: true }).fill("2026-11-15")
    await form.getByLabel("Instagram", { exact: true }).check()
    await form.getByRole("group", { name: "What format?", exact: true }).getByLabel("Carousel", { exact: true }).check()
    await form.getByRole("heading", { name: "When and where?", exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: `docs/media-guided-intake/screenshots/timing-${width}.png` })
    await form.getByRole("button", { name: "Continue", exact: true }).click()
    await form.getByRole("radio", { name: /Help me write it/ }).check()
    await form.getByRole("button", { name: "+ Add a link for readers", exact: true }).click()
    await form.getByLabel("Destination URL").fill("https://www.intercollegiatepsychedelics.net/mentorship/")
    await form.getByLabel("Where to include the link", { exact: true }).fill("Instagram bio and caption")
    await form.getByRole("heading", { name: "Copy and files", exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: `docs/media-guided-intake/screenshots/copy-${width}.png` })
    await form.getByRole("button", { name: "Remove reader link", exact: true }).click()
    await form.getByRole("button", { name: "+ Add a link for readers", exact: true }).click()
    await expect(form.getByLabel("Destination URL")).toHaveValue("")
    await expect(form.getByLabel("Where to include the link", { exact: true })).toHaveValue("")
    await form.getByRole("button", { name: "Remove reader link", exact: true }).click()
    await form.getByRole("button", { name: "Continue", exact: true }).click()
    await form.getByLabel("Notes for the Media team (optional)").fill("Please coordinate with the Community team before posting.")
    await form.getByRole("heading", { name: "Anything else?", exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: `docs/media-guided-intake/screenshots/review-${width}.png` })
    await expect(form.getByRole("button", { name: "Send request", exact: true })).toBeEnabled()
    await form.getByRole("button", { name: "Send request", exact: true }).scrollIntoViewIfNeeded()
    await expect(page.getByText("Integration status", { exact: true })).toHaveCount(0)
    await page.screenshot({ path: `docs/media-guided-intake/screenshots/footer-${width}.png` })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    await form.getByRole("button", { name: "Cancel", exact: true }).click()
    await expect(form).toHaveCount(0)
    expect(submissions).toBe(0)
    expect(errors).toEqual([])
    await expect(page.locator("nextjs-portal [data-nextjs-dialog]")).toHaveCount(0)
  })
}

test("integration diagnostics belong to the expense admin queue, not request forms or Media", async ({ page }) => {
  await page.goto("/workflow-preview/expenses")
  const status = page.getByText("Integration status", { exact: true })
  await expect(status).toBeVisible()
  await status.click()
  await expect(page.getByRole("button", { name: "Retry pending deliveries", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Submit expense", exact: true }).click()
  await expect(status).toHaveCount(0)
  await page.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(status).toBeVisible()
  await page.getByLabel("Preview as").selectOption("member")
  await expect(status).toHaveCount(0)
  await page.goto("/workflow-preview/media")
  await expect(page.getByRole("button", { name: "New media request", exact: true })).toBeEnabled()
  await expect(status).toHaveCount(0)
  await page.getByRole("button", { name: "New media request", exact: true }).click()
  await expect(status).toHaveCount(0)
})

test("a failed submission keeps the brief and reuses its id on retry", async ({ page }) => {
  await page.goto("/workflow-preview/media")
  await page.getByRole("button", { name: "New media request", exact: true }).click()
  const form = page.getByRole("form", { name: "New media request" })
  await form.getByLabel("Give it a name", { exact: true }).fill("Retry this brief")
  await form.getByLabel("What's it about?").fill("Retain my draft after a save failure.")
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  await form.getByLabel("Post by", { exact: true }).fill("2026-12-01")
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  await form.getByRole("radio", { name: /Help me write it/ }).check()
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  let release: () => void = () => {}
  const heldResponse = new Promise<void>((resolve) => { release = resolve })
  const ids: string[] = []
  await page.route("**/api/admin/workflows", async (route) => {
    if (route.request().method() !== "POST") return route.continue()
    ids.push(route.request().postDataJSON().id)
    if (ids.length === 1) await heldResponse
    await route.fulfill({ json: { ok: false, error: "Unable to save. Please retry." } })
  })
  await form.getByRole("button", { name: "Send request", exact: true }).click()
  await expect(form.getByRole("button", { name: "Sending…", exact: true })).toBeDisabled()
  await expect(form.getByRole("button", { name: "Back", exact: true })).toBeDisabled()
  release()
  await expect(form.getByRole("alert")).toHaveText("Unable to save. Please retry.")
  await expect(form.getByText("Retry this brief · Announcement", { exact: true })).toBeVisible()
  await form.getByRole("button", { name: "Send request", exact: true }).click()
  await expect(form.getByRole("alert")).toHaveText("Unable to save. Please retry.")
  expect(ids).toHaveLength(2)
  expect(ids[0]).toBe(ids[1])
})
