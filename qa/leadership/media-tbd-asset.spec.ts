import { test, expect, type Page } from "@playwright/test"

const shots = "docs/media-guided-intake/screenshots/tbd-asset"
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page, request }) => {
  await request.post("/api/admin/workflows", { data: { action: "reset_demo" } })
  const found: string[] = []
  errors.set(page, found)
  page.on("pageerror", (e) => found.push(e.message))
  page.on("console", (m) => { if (m.type() === "error") found.push(m.text()) })
})
test.afterEach(async ({ page }) => {
  expect(errors.get(page)).toEqual([])
  await expect(page.locator("nextjs-portal [data-nextjs-dialog]")).toHaveCount(0)
})

async function startRequest(page: Page, title: string) {
  await page.goto("/workflow-preview/media")
  await page.getByRole("button", { name: "New media request", exact: true }).click()
  const form = page.getByRole("form", { name: "New media request" })
  await form.getByLabel("Give it a name", { exact: true }).fill(title)
  await form.getByLabel("Team or project").fill("Media")
  await form.getByLabel("What's it about?").fill("Test brief for TBD and asset-only requests.")
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  return form
}

test("A: Post by needs a date or TBD; TBD shows in review, detail, list and calendar", async ({ page }) => {
  const form = await startRequest(page, "TBD post")
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(form.getByRole("alert")).toHaveText("Choose a post by date or mark it TBD.")
  await form.getByLabel("Date is TBD").check()
  await expect(form.getByLabel("Post by", { exact: true })).toBeDisabled()
  await form.getByRole("heading", { name: "When and where?", exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${shots}/after-when-tbd-1440.png` })
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  await form.getByRole("radio", { name: /Help me write it/ }).check()
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  const review = form.locator("dl")
  await expect(review.getByText("Post by", { exact: true })).toBeVisible()
  await expect(review.getByText("TBD", { exact: true })).toBeVisible()
  await form.getByRole("button", { name: "Send request", exact: true }).click()
  await expect(form).toHaveCount(0)
  const overview = page.getByRole("region", { name: "Request overview" })
  await expect(overview.getByText("Publish by date", { exact: true })).toBeVisible()
  await expect(overview.getByText("TBD", { exact: true })).toBeVisible()
  await page.goto("/workflow-preview/media")
  await expect(page.getByRole("row", { name: /TBD post/ }).getByText("TBD", { exact: true })).toBeVisible()
})

test("B + C: asset-only request with Needed by Dec 15, N/A and placeholder; toggle relabels before submit", async ({ page }) => {
  const form = await startRequest(page, "Partner media kit")
  const toggle = form.getByLabel(/Asset for partner\/internal use, not posted/)
  await toggle.check()
  await expect(form.getByLabel("Needed by", { exact: true })).toBeVisible()
  await expect(form.getByText("The day the asset should be ready, not a posting date.")).toBeVisible()
  const where = form.getByRole("group", { name: "Where will it be used?", exact: true })
  await expect(where.getByLabel("N/A", { exact: true })).toBeChecked()
  await expect(where.getByLabel("For partners: Instagram", { exact: true })).toBeVisible()
  await expect(where.getByLabel("Instagram", { exact: true })).toHaveCount(0)
  await toggle.uncheck()
  await expect(form.getByLabel("Post by", { exact: true })).toBeVisible()
  await expect(form.getByRole("group", { name: "Where should it go?", exact: true }).getByLabel("Media to advise", { exact: true })).toBeChecked()
  await toggle.check()
  await form.getByLabel("Needed by", { exact: true }).fill("2026-12-15")
  await form.getByLabel(/Placeholder, not ready for production/).check()
  await form.getByRole("heading", { name: "When and where?", exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${shots}/after-when-asset-1440.png` })
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(form.getByRole("heading", { name: "Partner captions and usage notes", exact: true })).toBeVisible()
  await form.getByLabel("Usage notes (optional)").fill("Partners may post on their own channels; tag IPN.")
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  const review = form.locator("dl")
  await expect(review.getByText("Needed by", { exact: true })).toBeVisible()
  await expect(review.getByText("Dec 15, 2026", { exact: true })).toBeVisible()
  await expect(review.getByText("Not ready for production", { exact: true })).toBeVisible()
  await expect(review.getByText("Asset for partner/internal use, not posted by IPN", { exact: true })).toBeVisible()
  await form.getByRole("button", { name: "Send request", exact: true }).click()
  await expect(form).toHaveCount(0)
  const overview = page.getByRole("region", { name: "Request overview" })
  await expect(overview.getByText("Needed by", { exact: true })).toBeVisible()
  await expect(overview.getByText("2026-12-15", { exact: true })).toBeVisible()
  await expect(overview.getByText("Placeholder, not ready for production", { exact: true })).toBeVisible()
  const production = page.getByRole("region", { name: "Production and publication" })
  const stages = production.getByLabel("Move request to")
  await expect(stages.locator("option", { hasText: "Delivered: Ready for partner use" })).toHaveCount(1)
  await expect(stages.locator("option", { hasText: "Published" })).toHaveCount(0)
  await expect(production.getByLabel("Published link")).toHaveCount(0)
})

test("C4 + C5: calendar lists TBD and asset-only requests; edits keep the same rules", async ({ page }) => {
  const form = await startRequest(page, "Office Hours update")
  await form.getByLabel("Date is TBD").check()
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  await form.getByRole("radio", { name: /Help me write it/ }).check()
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  await form.getByRole("button", { name: "Send request", exact: true }).click()
  await expect(form).toHaveCount(0)
  await page.getByRole("button", { name: "Edit request", exact: true }).click()
  const tbd = page.getByLabel("Date is TBD")
  await expect(tbd).toBeChecked()
  await tbd.uncheck()
  await page.getByLabel("Post by", { exact: true }).fill("2026-12-20")
  await page.getByLabel(/Asset for partner\/internal use, not posted/).check()
  await expect(page.getByLabel("Needed by", { exact: true })).toHaveValue("2026-12-20")
  await expect(page.getByLabel("N/A", { exact: true })).toBeChecked()
  await page.getByRole("button", { name: "Save changes", exact: true }).click()
  const overview = page.getByRole("region", { name: "Request overview" })
  await expect(overview.getByText("Needed by", { exact: true })).toBeVisible()
  await expect(overview.getByText("2026-12-20", { exact: true })).toBeVisible()
  await page.goto("/workflow-preview/media")
  const row = page.getByRole("row", { name: /Office Hours update/ })
  await expect(row.getByText("Needed by", { exact: true })).toBeVisible()
  await expect(row.getByText("Asset only, not posted by IPN", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Media calendar", exact: true }).click()
  const calendar = page.getByRole("region", { name: "Media calendar" })
  await expect(calendar.getByRole("heading", { name: "TBD and needed-by requests" })).toBeVisible()
  await expect(calendar.getByRole("button", { name: /Needed by Dec 20, 2026.*Office Hours update/ })).toBeVisible()
  await calendar.getByRole("heading", { name: "TBD and needed-by requests" }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${shots}/after-calendar-list-1440.png` })
})

test("mobile 390px: asset-only step fits without sideways scroll", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const form = await startRequest(page, "Mobile kit")
  await form.getByLabel(/Asset for partner\/internal use, not posted/).check()
  await form.getByLabel("Date is TBD").check()
  await form.getByRole("heading", { name: "When and where?", exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${shots}/after-when-asset-390.png` })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  for (const name of ["Date is TBD", "N/A"]) {
    const box = await form.getByLabel(name, { exact: true }).locator("xpath=ancestor::label[1]").boundingBox()
    expect(box!.height).toBeGreaterThanOrEqual(44)
  }
})
