import { test, expect, type Page } from "@playwright/test"

const shots = "docs/media-guided-intake/screenshots/drafts"
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page, request }) => {
  await request.post("/api/admin/workflows", { data: { action: "reset_demo" } })
  const found: string[] = []
  errors.set(page, found)
  page.on("pageerror", (e) => found.push(e.message))
  page.on("console", (m) => { if (m.type() === "error") found.push(m.text()) })
})
test.afterEach(async ({ page }) => {
  expect(errors.get(page)).toEqual([])
  await expect(page.locator("nextjs-portal [data-nextjs-dialog]")).toHaveCount(0)
})

async function open(page: Page) {
  await page.goto("/workflow-preview/media")
  await page.getByRole("button", { name: "New media request", exact: true }).click()
  return page.getByRole("form", { name: "New media request" })
}

test("Save draft works on every step with required fields empty, and the draft stays out of the queue", async ({ page }) => {
  const form = await open(page)
  const save = form.getByRole("button", { name: "Save draft", exact: true })
  // Step 1: nothing filled in at all.
  await save.click()
  await expect(form.getByRole("status")).toContainText("Draft saved")
  await expect(form.getByRole("alert")).toHaveCount(0)
  await form.getByLabel("Give it a name", { exact: true }).fill("Member Office Hours")
  await form.getByLabel("Team or project").fill("Community")
  await form.getByLabel("What's it about?").fill("Weekly office hours")
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  // Step 2: no date chosen yet.
  await expect(save).toBeVisible()
  await save.click()
  await expect(form.getByRole("status")).toContainText("Draft saved")
  await form.getByLabel("Date is TBD").check()
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  // Step 3: no copy choice yet.
  await expect(save).toBeVisible()
  await save.click()
  await expect(form.getByRole("status")).toContainText("Draft saved")
  await form.getByRole("radio", { name: /Help me write it/ }).check()
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  // Step 4: review.
  await expect(save).toBeVisible()
  await save.scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${shots}/wizard-review-1440.png` })
  await save.click()
  await expect(form.getByRole("status")).toContainText("Draft saved")
  await form.getByRole("button", { name: "Cancel" }).click()
  // Not in the queue or the calendar; listed under My drafts.
  await expect(page.getByRole("row", { name: /Member Office Hours/ })).toHaveCount(0)
  await page.getByRole("button", { name: /Media calendar/ }).click()
  await expect(page.getByText("Member Office Hours")).toHaveCount(0)
  await page.getByRole("button", { name: /My drafts \(1\)/ }).click()
  await expect(page.getByRole("heading", { name: "Member Office Hours" })).toBeVisible()
  await page.screenshot({ path: `${shots}/my-drafts-1440.png` })
})

test("Leaving with unsaved changes asks first; a draft reopens filled in and sends as a normal request", async ({ page }) => {
  let form = await open(page)
  await form.getByLabel("Give it a name", { exact: true }).fill("Vital")
  await form.getByRole("button", { name: "Cancel" }).click()
  await expect(page.getByRole("alertdialog", { name: "Unsaved changes" })).toBeVisible()
  await page.getByRole("button", { name: "Keep editing" }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${shots}/unsaved-changes-1440.png` })
  await page.getByRole("button", { name: "Save draft and close" }).click()
  await expect(form).toHaveCount(0)
  await page.getByRole("button", { name: /My drafts/ }).click()
  await page.getByRole("button", { name: "Continue editing: Vital" }).click()
  form = page.getByRole("form", { name: "New media request" })
  await expect(form.getByRole("heading", { name: "Continue your draft" })).toBeVisible()
  await expect(form.getByLabel("Give it a name", { exact: true })).toHaveValue("Vital")
  await form.getByLabel("Team or project").fill("Media")
  await form.getByLabel("What's it about?").fill("Vital launch")
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  await form.getByLabel("Post by", { exact: true }).fill("2026-12-20")
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  await form.getByRole("radio", { name: /Help me write it/ }).check()
  await form.getByRole("button", { name: "Continue", exact: true }).click()
  await form.getByRole("button", { name: "Send request", exact: true }).click()
  await expect(form).toHaveCount(0)
  await expect(page.getByRole("heading", { name: "Vital", exact: true })).toBeVisible()
  await page.goto("/workflow-preview/media")
  await expect(page.getByRole("row", { name: /Vital/ })).toBeVisible()
  await expect(page.getByRole("button", { name: "My drafts", exact: true })).toBeVisible()
})

