test("A draft can be deleted by its creator and other people never see it", async ({ page }) => {
  const form = await open(page)
  await form.getByLabel("Give it a name", { exact: true }).fill("Private idea")
  await form.getByRole("button", { name: "Save draft", exact: true }).click()
  await expect(form.getByRole("status")).toContainText("Draft saved")
  await form.getByRole("button", { name: "Cancel" }).click()
  await page.getByRole("button", { name: /My drafts/ }).click()
  await page.getByLabel("Preview as").selectOption("member")
  await page.getByRole("button", { name: /My drafts/ }).click()
  await expect(page.getByText("No drafts yet")).toBeVisible()
  await page.getByLabel("Preview as").selectOption("approver")
  await page.getByRole("button", { name: /My drafts/ }).click()
  await page.getByRole("button", { name: "Delete draft: Private idea" }).click()
  await expect(page.getByRole("alertdialog")).toBeVisible()
  await page.screenshot({ path: `${shots}/delete-confirm-1440.png` })
  await page.getByRole("button", { name: "Delete draft", exact: true }).click()
  await expect(page.getByText("No drafts yet")).toBeVisible()
  await page.screenshot({ path: `${shots}/empty-drafts-1440.png` })
})

test("mobile: Save draft stays reachable at 390px", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const form = await open(page)
  await form.getByLabel("Give it a name", { exact: true }).fill("Mobile draft")
  const save = form.getByRole("button", { name: "Save draft", exact: true })
  await save.scrollIntoViewIfNeeded()
  await expect(save).toBeVisible()
  await save.click()
  await expect(form.getByRole("status")).toContainText("Draft saved")
  await page.screenshot({ path: `${shots}/wizard-saved-390.png`, fullPage: true })
  await form.getByRole("button", { name: "Cancel" }).click()
  await page.getByRole("button", { name: /My drafts/ }).click()
  await page.screenshot({ path: `${shots}/my-drafts-390.png`, fullPage: true })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
})
