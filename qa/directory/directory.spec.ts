import { test, expect, type Page } from "@playwright/test"
const cards = (page: Page) => page.getByRole("button", { name: /^View .*'s profile/ })
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page, request }) => {
  await request.post("/api/directory-qa", { data: { reset: true } })
  const found: string[] = []; errors.set(page, found)
  page.on("pageerror", e => found.push(e.message))
  page.on("console", m => { if (m.type() === "error") found.push(m.text()) })
})
test.afterEach(async ({ page }) => {
  expect(errors.get(page)).toEqual([])
  await expect(page.locator("nextjs-portal [data-nextjs-dialog]")).toHaveCount(0)
})
for (const width of [1440, 1280, 390, 320]) test(`compact cards and complete names at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 950 })
  await page.goto("/dashboard/directory")
  await expect(cards(page)).toHaveCount(60)
  const maya = cards(page).first()
  await expect(maya).toContainText("Community Research Lab")
  await expect(maya).not.toContainText("Historical University")
  await expect(maya).not.toContainText("Neuroscience")
  const long = cards(page).nth(7)
  await expect(long).toContainText("Alexandria-Catherine Montgomery-Wellington")
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: info.outputPath(`directory-${width}.png`), fullPage: true })
  await long.scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath(`long-name-${width}.png`) })
  await maya.click()
  await expect(page.getByRole("dialog")).toContainText("Neuroscience")
  await expect(page.getByRole("dialog")).toContainText("Historical University")
  await page.screenshot({ path: info.outputPath(`profile-${width}.png`) })
  await page.keyboard.press("Escape")
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await expect(maya).toBeFocused()
})
for (const width of [1440, 390]) test(`Connect retains pages and scroll at ${width}px`, async ({ page, request }, info) => {
  await page.setViewportSize({ width, height: 950 })
  await page.goto("/dashboard/directory")
  await page.getByRole("button", { name: "Load more members", exact: true }).click()
  await expect(cards(page)).toHaveCount(120)
  await page.getByRole("button", { name: "Load more members", exact: true }).click()
  await expect(cards(page)).toHaveCount(125)
  const target = cards(page).last()
  await target.click()
  const scrollBefore = await page.locator(".overflow-y-auto").first().evaluate(el => el.scrollTop)
  await page.getByRole("button", { name: "Connect", exact: true }).click()
  await expect(page.getByText("Request sent", { exact: true })).toBeVisible()
  await expect(page.getByRole("dialog")).toBeVisible()
  await expect(cards(page)).toHaveCount(125)
  await page.screenshot({ path: info.outputPath(`request-sent-${width}.png`) })
  await page.getByRole("button", { name: "Close", exact: true }).click()
  expect(await page.locator(".overflow-y-auto").first().evaluate(el => el.scrollTop)).toBeCloseTo(scrollBefore, -1)
  await expect(target).toBeFocused()
  await expect(page.getByRole("button", { name: "Load more members" })).toHaveCount(0)
  await target.click()
  await page.getByRole("button", { name: "Cancel request", exact: true }).click()
  await page.getByRole("dialog", { name: "Cancel request?", exact: true }).getByRole("button", { name: "Cancel request", exact: true }).click()
  await expect(page.getByRole("button", { name: "Connect", exact: true })).toBeVisible()
  expect((await (await request.get("/api/directory-qa")).json()).connections).toHaveLength(0)
})
test("failed request retries, incoming request autoaccepts, removal clears contact", async ({ page, request }, info) => {
  await page.goto("/dashboard/directory")
  await cards(page).first().click()
  await request.post("/api/directory-qa", { data: { failNext: true } })
  await page.getByRole("button", { name: "Connect", exact: true }).click()
  await expect(page.getByRole("dialog").getByRole("alert")).toContainText("Simulated connection failure")
  await expect(page.getByRole("button", { name: "Connect", exact: true })).toBeEnabled()
  await request.post("/api/directory-qa", { data: { incoming: 0 } })
  await page.getByRole("button", { name: "Connect", exact: true }).click()
  await expect(page.getByText("Connected", { exact: true })).toBeVisible()
  await expect(page.locator('a[href="mailto:member-100@example.test"]')).toBeVisible()
  await page.screenshot({ path: info.outputPath("accepted-contact.png") })
  await page.getByRole("button", { name: "Remove connection", exact: true }).click()
  await page.getByRole("dialog", { name: "Remove connection?", exact: true }).getByRole("button", { name: "Remove connection", exact: true }).click()
  await expect(page.getByRole("button", { name: "Connect", exact: true })).toBeVisible()
  await expect(page.locator('a[href="mailto:member-100@example.test"]')).toHaveCount(0)
})
test("search changes reset pagination and clear search restores the first page", async ({ page }) => {
  await page.goto("/dashboard/directory")
  await page.getByRole("button", { name: "Load more members", exact: true }).click()
  await expect(cards(page)).toHaveCount(120)
  await page.getByRole("textbox").first().fill("Member 125")
  await expect(cards(page)).toHaveCount(1)
  await expect(cards(page).first()).toContainText("Member 125")
  await page.getByRole("textbox").first().fill("")
  await expect(cards(page)).toHaveCount(60)
})
test("load-more read failure preserves rows and retries", async ({ page, request }) => {
  await page.goto("/dashboard/directory")
  await request.post("/api/directory-qa", { data: { loadMoreFailure: true } })
  await page.getByRole("button", { name: "Load more members", exact: true }).click()
  await expect(page.getByText("More members could not load. Please try again.")).toBeVisible()
  await expect(cards(page)).toHaveCount(60)
  await page.getByRole("button", { name: "Load more members", exact: true }).click()
  await expect(cards(page)).toHaveCount(120)
})
test("accepted contact read failure is explicit and reopening retries", async ({ page, request }) => {
  await page.goto("/dashboard/directory")
  await cards(page).first().click()
  await request.post("/api/directory-qa", { data: { incoming: 0, contactFailure: true } })
  await page.getByRole("button", { name: "Connect", exact: true }).click()
  await expect(page.getByText("Connected", { exact: true })).toBeVisible()
  await expect(page.getByText(/Connected, but contact details could not load/)).toBeVisible()
  await expect(page.locator('a[href="mailto:member-100@example.test"]')).toHaveCount(0)
  await page.getByRole("button", { name: "Close", exact: true }).click()
  await request.post("/api/directory-qa", { data: { contactFailure: false } })
  await cards(page).first().click()
  await expect(page.locator('a[href="mailto:member-100@example.test"]')).toBeVisible()
})
