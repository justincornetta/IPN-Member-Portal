test("guest modal remains scrollable on a short phone viewport and backdrop dismissal restores focus",async({page})=>{
  await page.setViewportSize({width:390,height:600})
  await page.goto("/events/guest-rsvp-preview")
  const entry=page.getByRole("button",{name:"RSVP without an account",exact:true})
  await entry.click()
  const dialog=page.getByRole("dialog")
  const rect=await dialog.boundingBox()
  expect(rect!.height).toBeLessThanOrEqual(568)
  await dialog.getByRole("button",{name:"Confirm RSVP",exact:true}).scrollIntoViewIfNeeded()
  await expect(dialog.getByRole("button",{name:"Confirm RSVP",exact:true})).toBeInViewport()
  await page.screenshot({path:`${dir}/390-short-modal.png`})
  await page.mouse.click(2,2)
  await expect(dialog).not.toBeVisible()
  await expect(entry).toBeFocused()
})
