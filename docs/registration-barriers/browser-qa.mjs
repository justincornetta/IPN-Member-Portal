import { fileURLToPath } from 'node:url'
const { chromium } = await import(process.env.IPN_QA_PLAYWRIGHT_MODULE || 'playwright')
import assert from 'node:assert/strict'
const browser = await chromium.launch({headless:true})
const page = await browser.newPage()
const errors=[]; const submissions=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('console',m=>{if(m.type()==='error') errors.push(m.text())})
await page.route('**/api/portal-analytics',r=>r.fulfill({json:{ok:true}}))
await page.route('**/api/locations/verify',r=>r.fulfill({json:{candidates:[]}}))
await page.route('**/register',async r=>{
 if(r.request().method()==='POST') {
  submissions.push(r.request().postData())
  await r.fulfill({status:200,contentType:'text/x-component',body:'0:{"a":"$@1","f":[],"b":"fixture"}\n1:{"error":"Isolated QA submission captured"}\n'})
 } else await r.continue()
})
await page.goto(`${process.env.IPN_QA_BASE_URL || 'http://localhost:3147'}/register`)
for(const [name,value] of Object.entries({first_name:'Local',last_name:'Fixture',email:'fixture@example.invalid',password:'fixture-password',confirm_password:'fixture-password'})) await page.locator(`[name="${name}"]`).fill(value)
await page.getByRole('button',{name:'Next',exact:true}).click()
await page.locator('#country').selectOption('Germany')
await page.getByRole('combobox',{name:/City/}).fill('Berlin')
await page.locator('#persona').selectOption('Professional in another field')
await page.getByRole('button',{name:'Next',exact:true}).click()
await page.getByRole('radio',{name:'Health & Medicine',exact:true}).check()
const yes='Yes — I currently work in the field', notyet="Not yet — I'm interested in working in the field", no="No — I don't plan to work in the field", unsure="I'm not sure", choice="I'm not interested in the field"
for(const status of [notyet,no,unsure]) {
 await page.getByRole('radio',{name:status,exact:true}).check()
 await page.getByRole('button',{name:'Next',exact:true}).click()
 await page.getByText('Please select at least one reason.',{exact:true}).waitFor()
 assert.equal(await page.locator('#registration-step-heading').textContent(),'Step 3 of 4: Background')
 await page.getByRole('checkbox',{name:choice,exact:true}).check()
 await page.getByRole('button',{name:'Next',exact:true}).click()
 assert.equal(await page.locator('#registration-step-heading').textContent(),'Step 4 of 4: About You')
 await page.getByRole('button',{name:'Back',exact:true}).click()
 await page.getByRole('checkbox',{name:choice,exact:true}).uncheck()
}
const labels=await page.getByRole('checkbox').evaluateAll(nodes=>nodes.map(n=>n.value))
assert.deepEqual(labels.slice(-2),[choice,'Other'])
await page.getByRole('checkbox',{name:choice,exact:true}).check()
await page.screenshot({path:fileURLToPath(new URL('./background.png', import.meta.url)),fullPage:true})
await page.getByRole('checkbox',{name:'Other',exact:true}).check()
await page.locator('#barriers_other').fill('Local fixture detail')
await page.getByRole('button',{name:'Next',exact:true}).click()
await page.getByRole('radio',{name:'Social Media',exact:true}).check()
await page.getByRole('button',{name:/Create account/i}).click()
await page.getByText('Isolated QA submission captured',{exact:true}).waitFor()
assert.ok(submissions[0].includes(choice))
await page.getByRole('button',{name:'Back',exact:true}).click()
await page.getByRole('radio',{name:yes,exact:true}).check()
assert.equal(await page.getByRole('checkbox').count(),0)
await page.getByRole('radio',{name:notyet,exact:true}).check()
assert.equal(await page.getByRole('checkbox',{name:choice,exact:true}).isChecked(),false)
assert.equal(await page.getByRole('checkbox',{name:'Other',exact:true}).isChecked(),false)
assert.equal(await page.locator('#barriers_other').count(),0)
await page.getByRole('button',{name:'Next',exact:true}).click()
await page.getByText('Please select at least one reason.',{exact:true}).waitFor()
await page.getByRole('radio',{name:yes,exact:true}).check()
await page.getByRole('button',{name:'Next',exact:true}).click()
await page.getByRole('button',{name:/Create account/i}).click()
await page.getByText('Isolated QA submission captured',{exact:true}).waitFor()
assert.ok(submissions[1].includes('"psychedelic_field_barriers":[]'))
assert.deepEqual(errors,[])
console.log(JSON.stringify({passed:true,paths:['Yes','No','Not yet','Not sure'],capturedSubmissions:submissions.length,consoleErrors:errors,pageErrors:errors}))
await browser.close()
